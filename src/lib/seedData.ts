/** Gera e-mail e handle a partir do nome, só para o cenário parecer completo. */
function contactHandles(name: string): { email: string; instagram: string } {
  const slug = name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[^a-z ]/g, '')
    .trim()
    .split(/\s+/)
    .join('.')
  return { email: `${slug}@email.com`, instagram: `@${slug.replace(/\./g, '')}` }
}

