/** O que registrar quando um lead alcança cada etapa. */
const STAGE_ACTIVITY: Record<LeadStage, { type: LeadActivity['type']; title: string }> = {
  [LeadStage.NEW]: { type: 'note', title: 'Lead cadastrado' },
  [LeadStage.CONTACTED]: { type: 'contact', title: 'Primeiro contato enviado' },
  [LeadStage.REPLIED]: { type: 'message', title: 'Lead respondeu' },
  [LeadStage.MEETING]: { type: 'meeting', title: 'Reunião agendada' },
  [LeadStage.PROPOSAL_SENT]: { type: 'proposal', title: 'Proposta enviada' },
  [LeadStage.NEGOTIATION]: { type: 'message', title: 'Negociação iniciada' },
  [LeadStage.CLOSED]: { type: 'stage_change', title: 'Negócio fechado' },
  [LeadStage.LOST]: { type: 'stage_change', title: 'Oportunidade perdida' },
}

/**
 * Reconstrói o histórico de cada lead a partir da etapa em que ele está:
 * uma entrada por etapa percorrida, distribuída entre o cadastro e o último
 * contato registrado.
 */
const leadActivities: LeadActivity[] = leads.flatMap((lead) => {
  const reached = LEAD_STAGE_ORDER.slice(0, LEAD_STAGE_ORDER.indexOf(lead.stage) + 1)
  const start = new Date(`${lead.createdAt}`).getTime()
  const end = new Date(`${lead.updatedAt}`).getTime()
  const span = Math.max(end - start, 0)

  return reached.map((stage, index) => {
    const template = STAGE_ACTIVITY[stage]
    const ratio = reached.length > 1 ? index / (reached.length - 1) : 0
    const date = new Date(start + span * ratio).toISOString()
    return {
      id: `${lead.id}_act${index + 1}`,
      leadId: lead.id,
      type: template.type,
      title: template.title,
      description: index === 0 ? lead.desiredService : null,
      date: date.slice(0, 10),
      createdAt: date,
    }
  })
})

