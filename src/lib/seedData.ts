/**
 * Deriva o checklist do status, exatamente como o Kanban de produção faz ao
 * arrastar um card. `extra` marca etapas opcionais (legendas, motion, cor).
 */
function checklistFor(status: VideoStatus, extra: VideoChecklistKey[] = []): VideoChecklist {
  const checklist = applyStatusToChecklist(status)
  for (const key of extra) checklist[key] = true
  return checklist
}

